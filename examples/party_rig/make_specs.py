def waveguide_step(path):
    """Horn face panel + simplified elliptical OS waveguide, in pole-box coordinates (mm)."""
    import gmsh
    T = PB["T"]
    th, fd, p0, p1, n, M = pole_geom()
    ta, tb, r0, depth, wall = np.tan(np.radians(55.4)), np.tan(np.radians(47.9)), 12.7, 110.0, 6.0
    gmsh.initialize()
    try:
        gmsh.option.setNumber("General.Terminal", 0)
        occ = gmsh.model.occ
        # canonical frame: horn axis +x, throat at x = 0, mouth (outer face plane) at x = depth; y across, z along the face
        def loft(us, grow, x_end=None):
            wires = []
            for u in us:
                a = np.sqrt(r0 ** 2 + (u * ta) ** 2) + grow
                b = np.sqrt(r0 ** 2 + (u * tb) ** 2) + grow
                e = occ.addEllipse(u, 0, 0, max(a, b), min(a, b), zAxis=[1, 0, 0], xAxis=[0, 1, 0] if a >= b else [0, 0, 1])
                wires.append(occ.addCurveLoop([e]))
            return [v[1] for v in occ.addThruSections(wires, makeSolid=True, makeRuled=False) if v[0] == 3]
        us = np.linspace(0, depth, 12)
        bore = loft(np.r_[-2, us[1:], depth + 3], 0)                       # air, slightly past both ends
        # The waveguide is modelled as a solid plug filling the wedge behind the face (bore cut out): the air around
        # the printed shell is sealed bay air either way, and a 6 mm curved shell meshes badly at practical h.
        plug = [occ.addBox(-6, -166, -130, depth - T + 1 + 6, 332, 260)]
        face = [occ.addBox(depth - T, -166, -160, T, 332, 320)]             # face panel (long; ends trimmed below)
        bore += [occ.addCylinder(-8, 0, 0, 8.5, 0, 0, 16.0)]                  # 32 mm hole for the DE250 exit (25.4 mm piston in it)
        solid, _ = occ.fuse([(3, s) for s in plug], [(3, s) for s in face])
        solid, _ = occ.cut(solid, [(3, s) for s in bore])
        # into pole-box coordinates: rotate the axis to n (43 deg down) about y, then move the mouth centre to M
        occ.rotate(solid, 0, 0, 0, 0, 1, 0, th)
        occ.translate(solid, M[0] - depth * np.cos(th), 180, M[1] + depth * np.sin(th))
        # trim the face panel's ends horizontal (bevelled 43 deg, as cut), so it sits on the baffle and under the lip
        cut1 = occ.addBox(0, -10, p0[1] - 200, 600, 400, 200)
        cut2 = occ.addBox(0, -10, p1[1], 600, 400, 100)
        solid, _ = occ.cut(solid, [(3, cut1), (3, cut2)])
        occ.synchronize()
        gmsh.write(path)
    finally:
        gmsh.finalize()


