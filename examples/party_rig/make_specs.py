"""Write the party-rig cabinet specs (panel lists for `spkmod cad`) from the design project's data.

Sources (Subwoofer Design project, /mnt/project-files):
  subs      outdoor_sub/horn_<name>.json fold_params + outdoor_sub/fold3.py (straight-cut 3-layer tapped horn)
  low-mid   outdoor_lowmid/build_section.py (side section polygons, straight-cut build, 18 mm ply)
  pole box  outdoor_tops/pole_box_cutlist.md (15 mm ply, 43 deg waveguide wedge)
  fill      outdoor_fills/page.html (140 x 560 x 180 mm, 12 mm ply, 2 x PC105-4 110 mm apart)
Also writes cad/waveguide_face.step (horn face panel + simplified 120 x 70 waveguide) for the pole box.

usage: python make_specs.py [path to outdoor_sub folder]   (needs gmsh for the waveguide STEP)
"""
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
SPECS = os.path.join(HERE, "cad", "specs")
SUBDIR = sys.argv[1] if len(sys.argv) > 1 else "/mnt/project-files/outdoor_sub"
os.makedirs(SPECS, exist_ok=True)

# 12-280-W: Sd and cut-out from the sub thread's driver model (acoustic_net.py D12) and cut lists.
# Motor size is an ESTIMATE (no datasheet drawing in the project): check against the real driver.
D12 = dict(sd_cm2=510.7, cutout=282, thickness=8, motor=[156, 70])


def f(v):
    return float(round(v, 1))


def box(name, at, size):
    return "  - {type: box, name: %s, at: [%s], size: [%s]}" % (name, ", ".join(str(f(v)) for v in at), ", ".join(str(f(v)) for v in size))


def prism(name, pts, ext, plane="xz"):
    p = ", ".join("[%s, %s]" % (f(a), f(b)) for a, b in pts)
    return "  - {type: prism, name: %s, plane: %s, points: [%s], extrude: [%s, %s]}" % (name, plane, p, f(ext[0]), f(ext[1]))


def vec(v, nd=4):
    return "[%s]" % ", ".join(str(round(float(x), nd)) for x in v)


# ------------------------------------------------------------------ tapped-horn subs
def sub_spec(name):
    H = json.load(open(os.path.join(SUBDIR, f"horn_{name}.json")))
    p = H["fold_params"]
    T = 18.0
    Dx, Hz, yb, yf, zb, zf, gf, gb = (1000 * p[k] for k in ("Dx", "Hz", "yb", "yf", "zb", "zf", "gf", "gb"))
    W, Lx, Hx, Wx = 550 - 2 * T, Dx + 2 * T, Hz + 2 * T, 550.0
    y = lambda s: yf + (yb - yf) * s / Dx          # D1 underside above the inside floor, s = distance back from the front wall's inside face
    z = lambda s: zf + (zb - zf) * s / Dx          # D0 underside
    xs = Dx - gb - T                                # stub front face
    xd = xs - 170.0                                 # driver centre (fold3.py XD_OFF)
    X = lambda s: Dx + T - s                        # local x: back wall outer face at 0, mouth end at Lx
    Z = lambda h: T + h
    hm = lambda s: z(s) - y(s) - T
    ht = lambda s: Hz - z(s) - T
    # D1 slope -> baffle normal (front of cone points up into the middle layer)
    sl = (yb - yf) / Dx
    n = np.array([sl, 0, 1.0]); n /= np.linalg.norm(n)
    c = np.array([X(xd), Wx / 2, Z(y(xd)) + T / 2 * n[2]])
    o = 2.0   # overlap (mm) so touching panels fuse without leaks
    d1 = [(X(-o), Z(y(-o))), (X(xs + T), Z(y(xs + T))), (X(xs + T), Z(y(xs + T)) + T), (X(-o), Z(y(-o)) + T)]
    d0 = [(X(gf), Z(z(gf))), (X(xs + T), Z(z(xs + T))), (X(xs + T), Z(z(xs + T)) + T), (X(gf), Z(z(gf)) + T)]
    stub = [(X(xs), Z(y(xs)) + T - o), (X(xs + T), Z(y(xs + T)) + T - o), (X(xs + T), Z(z(xs + T)) + o), (X(xs), Z(z(xs)) + o)]
    path = [("closed throat stub (middle layer, behind the driver)", W * hm(xs), W * hm(xd), 170.0),
            ("middle layer forward to the front gap", W * hm(xd), W * hm(gf / 2), xd - gf / 2),
            ("front gap, up into the top layer", W * gf, W * gf, 0.5 * (hm(0) + ht(0)) + T),
            ("top layer backward", W * ht(gf / 2), W * ht(Dx - gb / 2), Dx - gb / 2 - gf / 2),
            ("back channel, down to the bottom layer", W * gb, W * gb, 0.5 * ht(Dx) + hm(Dx) + 2 * T + 0.5 * y(Dx)),
            ("bottom layer forward past the driver's motor", W * y(Dx - gb / 2), W * y(xd), Dx - gb / 2 - xd),
            ("bottom layer forward to the mouth", W * y(xd), W * y(0), xd)]
    air_1d = sum(0.5 * (a + b) * L for _, a, b, L in path) / 1e6
    L = [f"name: {name}", "units: mm",
         f"# {name} straight-cut tapped horn, 1 x 12-280-W. Generated by make_specs.py from {name} fold_params",
         f"#   (horn_{name}.json, model outdoor_sub/fold3.py). External {Lx:.0f} long x {Wx:.0f} wide x {Hx:.0f} high, 18 mm MDF.",
         "# orientation: lying flat as in the stack. x = length, back wall at x = 0, mouth end at x = %.0f;" % Lx,
         "#   y = width (0..550); z = up, bottom face on the ground at z = 0.",
         "# SELF-CHECK (HANDOVER 3.7)",
         "# 1. Air path, driver to mouth (internal width %.0f mm throughout; areas in cm2, lengths in mm, as in fold3.py):" % W]
    for nm, a, b, l in path:
        L.append("#    %-48s %6.0f -> %6.0f cm2 (%.0f x %.0f -> %.0f mm high), %4.0f mm" % (nm, a / 100, b / 100, W, a / W, b / W, l))
    L += ["#    Front of the cone feeds the middle layer (piston axis up, +z, tilted %.1f deg with D1); the rear" % np.degrees(np.arctan(sl)),
          "#    and motor sit in the bottom layer (S3 at the driver), as in the 1D model.",
          "# 2. Net air: design %d L (horn_%s.json air_litres); the 1D path sum gives %.0f L." % (H.get("air_litres", round(air_1d)), name, air_1d),
          "#    Expect outer box %.1f L - wood (spkmod cad prints it) - motor ~1.3 L to land within ~3 %% of that." % (Lx * Wx * Hx / 1e6),
          "# 3. Every internal panel spans the full inner width (y 18..532) and overlaps its neighbours by 2 mm.",
          "#    Left out (not in the air path or < 1 %% of the section): 6 brace blocks 60 x 100 set on edge in line",
          "#    with the flow, the gasketed driver hatch (flush), glue fillets, the 12 mm mouth round-over, handles, castors.",
          "# 4. Mouth: the open slot at the front, x = %.0f, y 18..532, z 18..%.0f (%.0f x %.0f mm)." % (Lx, Z(yf), W, yf),
          "#    Piston 'drv': centre %s mm (mid-thickness of D1, %.0f mm from the front wall's inside face), front = up." % (vec(c, 1), xd),
          "parts:",
          box("side_l", [0, 0, 0], [Lx, T, Hx]), box("side_r", [0, Wx - T, 0], [Lx, T, Hx]),
          box("bottom", [0, T, 0], [Lx, W, T]), box("top", [0, T, Hx - T], [Lx, W, T]),
          box("back", [0, T, T], [T, W, Hz]),
          box("front", [Lx - T, T, Z(yf)], [T, W, Hz - yf]),
          prism("d1_driver_divider", d1, (T, T + W)),
          prism("d0_upper_divider", d0, (T, T + W)),
          prism("stub", stub, (T, T + W)),
          "cutouts:",
          "  - {type: cylinder, name: drv_hole, center: %s, axis: %s, diameter: %d, depth: 40}" % (vec(c, 1), vec(n), D12["cutout"]),
          "pistons:",
          "  - {name: drv, center: %s, axis: %s, sd_cm2: %s, cutout: %d, thickness: %d, motor: %s}   # motor size estimated"
          % (vec(c, 1), vec(n), D12["sd_cm2"], D12["cutout"], D12["thickness"], D12["motor"])]
    open(os.path.join(SPECS, f"{name}.yml"), "w").write("\n".join(L) + "\n")
    return dict(Lx=Lx, Wx=Wx, Hx=Hx, mouth_h=yf, mouth_zc=T + yf / 2)


