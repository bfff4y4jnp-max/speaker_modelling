def pole_geom():
    T, D = PB["T"], PB["D"]
    th = np.radians(PB["ang"])
    face_dir = np.array([np.sin(th), np.cos(th)])       # along the horn face (x, z): up and forward, 47 deg from horizontal
    p0 = np.array([D, 575.0])                           # bottom front edge of the face, on top of the baffle
    p1 = p0 + 260 * face_dir                            # top front edge (x 397, z 765)
    n = np.array([np.cos(th), -np.sin(th)])             # outward face normal: forward and 43 deg down (horn axis)
    M = (p0 + p1) / 2                                   # mouth centre on the outer face plane
    return th, face_dir, p0, p1, n, M


